import pg from 'pg';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
try{process.loadEnvFile('.env.local');}catch { /* CI may provide environment variables without a local file. */ }
const db=new pg.Client({connectionString:process.env.MIGRATION_DATABASE_URL});await db.connect();
try {
 const {rows}=await db.query("SELECT table_name,column_name,data_type,udt_name,is_nullable,column_default FROM information_schema.columns WHERE table_schema='app' ORDER BY table_name,ordinal_position");
 const tables={};for(const r of rows)(tables[r.table_name]??=[]).push(r);
 const map=r=>r.data_type==='ARRAY'?'string[]':['jsonb','json'].includes(r.udt_name)?'Json':r.udt_name==='bool'?'boolean':['int2','int4','float4','float8'].includes(r.udt_name)?'number':'string';
 const hash=createHash('sha256').update(JSON.stringify(rows)).digest('hex');
 let output=`// Generated by scripts/db-types.mjs from live PostgreSQL catalog. Do not hand edit.\n// Schema fingerprint: ${hash}\nexport type Json = null | boolean | number | string | Json[] | {[key: string]: Json};\nexport interface Database {\n  app: {\n    Tables: {\n`;
 for(const [name,cols] of Object.entries(tables)){
  output+=`      ${name}: {\n        Row: {\n`;
  for(const r of cols)output+=`          ${r.column_name}: ${map(r)}${r.is_nullable==='YES'?' | null':''};\n`;
  output+='        };\n        Insert: {\n';
  for(const r of cols)output+=`          ${r.column_name}${r.is_nullable==='YES'||r.column_default?'?':''}: ${map(r)}${r.is_nullable==='YES'?' | null':''};\n`;
  output+='        };\n      };\n';
 }
 output+='    };\n  };\n}\nexport type TableName = keyof Database["app"]["Tables"];\nexport type Row<T extends TableName> = Database["app"]["Tables"][T]["Row"];\nexport type Insert<T extends TableName> = Database["app"]["Tables"][T]["Insert"];\n';
 const path='src/types/database.ts';
 if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==output)throw new Error('DATABASE_TYPE_DRIFT');console.log(`Types match ${Object.keys(tables).length} tables.`);}
 else {writeFileSync(path,output);console.log(`Generated types for ${Object.keys(tables).length} tables.`);}
}finally{await db.end();}
