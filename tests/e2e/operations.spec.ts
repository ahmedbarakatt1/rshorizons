import {test, expect} from "@playwright/test";
import {readFileSync} from "node:fs";
import {spawnSync} from "node:child_process";

test("staff operates a real resource and reviews a pending request", async ({page},info) => {
  test.skip(info.project.name!=="chromium" || process.env.E2E_LOCAL_STAFF!=="1","Local operator grant is an explicit development-only fixture.");
  const bootstrap=spawnSync(process.execPath,["scripts/bootstrap-local-operator.mjs"],{encoding:"utf8",env:process.env,windowsHide:true});
  expect(bootstrap.status,bootstrap.stderr).toBe(0);
  // Create this journey's own plain tour request. An unrelated photography
  // request legitimately needs a staffed photographer before approval.
  await page.goto("/en/experiences/boat-tours");
  await page.getByRole("link",{name:"Request this experience",exact:true}).click();
  await page.getByRole("button",{name:"Calculate my quote",exact:true}).click();
  await page.getByLabel("Full name",{exact:true}).fill("Local staff journey guest");
  await page.getByLabel("Email",{exact:true}).fill("staff-journey@example.test");
  await page.getByLabel("Participant 1",{exact:true}).fill("Local staff journey guest");
  await page.getByLabel("I accept the terms").check();await page.getByLabel("I have read the privacy notice").check();
  const created=page.waitForResponse(response=>response.url().endsWith("/api/v1/bookings")&&response.request().method()==="POST");
  await page.getByRole("button",{name:"Send reservation request",exact:true}).click();
  const reservation=await created;expect(reservation.status()).toBe(201);
  const reference=(await reservation.json()).data.reference;
  const grant=JSON.parse(readFileSync(".local/operator-access.json","utf8")) as {token:string};
  await page.goto("/admin");
  await page.getByText("Local operator access",{exact:true}).click();
  await page.getByLabel("Local operator token").fill(grant.token);
  await page.getByRole("button",{name:"Open local workspace"}).click();
  await expect(page.getByRole("heading",{name:"Reservation overview"})).toBeVisible();
  await expect(page.locator(".admin-kpis dd").first()).not.toHaveText("—");
  await page.screenshot({path:".local/evidence/ui/admin-overview-desktop.png",fullPage:true});
  await page.goto("/admin/operations");
  await page.getByRole("button",{name:"Create resource"}).click();
  const name=`UI test guide ${Date.now()}`;
  await page.getByLabel("Resource name",{exact:true}).fill(name);
  await page.getByRole("combobox",{name:"Kind",exact:true}).selectOption("guide");
  await page.getByRole("combobox",{name:"Capacity model",exact:true}).selectOption("exclusive");
  await page.getByLabel("Resource code",{exact:true}).fill(`ui-guide-${Date.now()}`);
  await page.getByRole("button",{name:"Save",exact:true}).click();
  await expect(page.getByRole("cell",{name,exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Create resource",exact:true}).click();
  const vehicleName=`UI test vehicle ${Date.now()}`;
  await page.getByLabel("Resource name",{exact:true}).fill(vehicleName);
  await page.getByRole("combobox",{name:"Kind",exact:true}).selectOption("vehicle");
  await page.getByRole("combobox",{name:"Capacity model",exact:true}).selectOption("exclusive");
  await page.getByLabel("Resource code",{exact:true}).fill(`ui-vehicle-${Date.now()}`);
  await page.getByLabel("Vehicle passenger seats",{exact:true}).fill("8");
  await page.getByLabel("Vehicle luggage capacity",{exact:true}).fill("10");
  await page.getByRole("combobox",{name:"Vehicle type",exact:true}).selectOption("van");
  const vehicleSaved=page.waitForResponse(response=>response.url().endsWith("/api/v1/admin/resources")&&response.request().method()==="POST");
  await page.getByRole("button",{name:"Save",exact:true}).click();
  const vehicleResponse=await vehicleSaved;
  expect(vehicleResponse.status()).toBe(201);
  expect(vehicleResponse.request().postDataJSON().metadata).toEqual({seats:8,luggage:10,vehicleKind:"van"});
  await expect(page.getByRole("cell",{name:vehicleName,exact:true})).toBeVisible();
  await page.goto("/admin/apartments");
  await page.getByRole("button",{name:"Manage",exact:true}).first().click();
  await expect(page.getByLabel("Check-in time",{exact:true})).toHaveValue(/\d{2}:\d{2}/);
  await expect(page.getByLabel("Cleaning fee in minor units",{exact:true})).toBeVisible();
  await expect(page.getByRole("group",{name:"Amenities",exact:true})).toBeVisible();
  await page.goto("/admin/bookings");
  await page.getByLabel("Reservation status").selectOption("pending_review");
  await page.locator(".admin-table tbody tr").filter({hasText:reference}).getByRole("link").click();
  await expect(page.getByRole("heading",{name:"Staff decision"})).toBeVisible();
  await page.screenshot({path:".local/evidence/ui/admin-booking-desktop.png",fullPage:true});
  await page.getByRole("combobox",{name:"Decision",exact:true}).selectOption("approve");
  await page.getByLabel("Reason or internal note").fill("Isolated local browser verification");
  const approved=page.waitForResponse(response=>response.url().endsWith("/approve")&&response.request().method()==="POST");
  await page.getByRole("button",{name:"Save",exact:true}).first().click();
  const approvalResponse=await approved;expect(approvalResponse.status(),await approvalResponse.text()).toBe(200);
  await expect(page.locator(".admin-title-row .status")).toContainText(/approved pending payment|confirmed/);
  await page.goto("/admin/content");
  await page.getByRole("button",{name:"Manage",exact:true}).first().click();
  await page.getByText("Variants, rates and payment policies",{exact:true}).click();
  await expect(page.getByRole("heading",{name:"Create experience variant",exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:".local/evidence/ui/admin-content-mobile.png",fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

test("apartment dates and transfer requests quote on the server",async({page})=>{
  await page.goto("/en/apartments");
  await page.getByLabel("Check-in",{exact:true}).fill("2027-06-01");
  await page.getByLabel("Check-out",{exact:true}).fill("2027-06-05");
  const availability=page.waitForResponse(response=>response.url().includes("/api/v1/apartments?"));
  await page.getByRole("button",{name:"Check availability"}).click();
  expect((await availability).status()).toBe(200);
  await page.locator(".catalog-card a").filter({has:page.getByRole("heading",{name:"Marina studio",exact:true})}).click();
  await page.getByRole("link",{name:"Request this stay"}).click();
  await page.getByLabel("Check-in",{exact:true}).fill("2027-06-01");
  await page.getByLabel("Check-out",{exact:true}).fill("2027-06-05");
  await page.getByRole("button",{name:"Calculate my quote"}).click();
  await expect(page.getByRole("heading",{name:"Your quote"})).toBeVisible();
  await page.goto("/en/transportation");
  await page.locator(".catalog-card a").first().click();
  await page.getByRole("link",{name:"Request this experience"}).click();
  await expect(page.getByLabel("Pickup address",{exact:true})).toBeVisible();
  await expect(page.getByLabel("Destination address",{exact:true})).toBeVisible();
});
