import {afterAll,beforeAll,expect,test,vi} from "vitest";
import {randomUUID} from "node:crypto";
import {readFile} from "node:fs/promises";
import {spawnSync} from "node:child_process";
import {route} from "@/server/api/router";
import {deliverNotification} from "@/integrations/messaging/notifications";
import {admin,makeDeparture,tourItem} from "../database/helpers";
const db=admin(),base="http://127.0.0.1:3000";
beforeAll(()=>db.connect());afterAll(()=>{vi.unstubAllEnvs();return db.end();});
test("a submitted booking creates one durable acknowledgement with the saved contact and private management link",async()=>{
  vi.stubEnv("EMAIL_PROVIDER","local");vi.stubEnv("APP_ENV","test");vi.stubEnv("DEMO_MODE","true");
  const seeded=spawnSync(process.execPath,["scripts/seed-local-notifications.mjs"],{env:process.env,encoding:"utf8",windowsHide:true});
  expect(seeded.status,seeded.stderr).toBe(0);
  const departure=await makeDeparture(db),item=await tourItem(db,departure.id);
  const request=async(path:string,body:unknown,key:string,cookie="")=>route(new Request(`${base}/api/v1/${path}`,{method:"POST",headers:{origin:base,cookie,"content-type":"application/json","idempotency-key":key},body:JSON.stringify(body)}),[path]);
  const quoted=await request("quotes",{locale:"en",paymentPolicy:"arrival",items:[item]},randomUUID());
  expect(quoted.status).toBe(201);
  const quote=(await quoted.json()).data;
  const cookie=quoted.headers.getSetCookie().map(v=>v.split(";")[0]).join("; ");
  const key=randomUUID(),email=`booking-${randomUUID()}@example.invalid`;
  const input={quoteId:quote.id,guest:{fullName:"Synthetic message guest",email,phoneE164:"+201234567890",locale:"en"},participants:[{displayName:"Synthetic message guest",ageCategory:"adult"}],consents:{termsAccepted:true,termsVersion:quote.policyVersions.terms,privacyNoticeVersion:quote.policyVersions.privacy,whatsappBookingUpdates:false,marketing:false,publicMediaUse:false}};
  const submitted=await request("bookings",input,key,cookie);expect(submitted.status).toBe(201);
  const booking=(await submitted.json()).data;
  expect(booking.status).toBe("pending_review");expect(booking.paymentRequested).toBe(false);
  expect((await request("bookings",input,key,cookie)).status).toBe(201);
  const events=(await db.query("SELECT e.id,e.aggregate_id,e.event_type,e.payload FROM app.outbox_events e JOIN app.bookings b ON b.id=e.aggregate_id WHERE b.reference=$1 AND e.event_type='request_received'",[booking.reference])).rows;
  expect(events).toHaveLength(1);
  const contact=(await db.query("SELECT g.email,g.phone_e164 FROM app.guests g JOIN app.bookings b ON b.primary_guest_id=g.id WHERE b.reference=$1",[booking.reference])).rows[0];
  expect(contact).toEqual({email,phone_e164:"+201234567890"});
  const job=(await db.query("INSERT INTO app.jobs(event_id,kind,job_key,status,attempts,lease_owner,lease_until) VALUES($1,'notification',$2,'running',1,'test',now()+interval '2 minutes') RETURNING id,attempts",[events[0].id,randomUUID()])).rows[0];
  const result=await deliverNotification({...job,event:events[0]}) as {messageId:string};
  expect(result).toMatchObject({external:false,status:"accepted",channel:"email"});
  const preview=JSON.parse(await readFile(`.local/outbox/${result.messageId.slice(6)}.json`,"utf8"));
  expect(`${preview.subject}\n${preview.text}`).toContain(booking.reference);expect(preview.text).toContain("/guest-access#token=");
  expect(await deliverNotification({...job,event:events[0]})).toEqual({alreadyProcessed:true});
  expect((await db.query("SELECT count(*)::int n FROM app.notification_deliveries WHERE job_id=$1",[job.id])).rows[0].n).toBe(1);
});
